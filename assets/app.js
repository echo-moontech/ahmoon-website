        function switchLang(lang) {
            // 切换语言 = 跳转到对应语言的 URL（内页跳该语言首页）
            var _p = location.pathname;
            var _isHome = (_p === '/' || _p === '/index.html'
                           || _p === '/zh/' || _p === '/zh/index.html'
                           || _p === '/es/' || _p === '/es/index.html');
            var _target;
            if (_isHome) {
                _target = lang === 'en' ? '/' : '/' + lang + '/';
            } else {
                _target = lang === 'en' ? '/' : '/' + lang + '/';
            }
            if (_target !== _p && _target !== _p.replace(/index\.html$/, '')) {
                try { localStorage.setItem('moonLang', lang); } catch (e) {}
                location.href = _target;
                return;
            }
            window.currentLang = lang;
            localStorage.setItem('moonLang', lang);

            // Update title
            document.title = window.translations[lang].pageTitle || document.title;

            // Update all data-i18n elements (text content)
            // Fix: if element contains an <a> child, only update the <a>'s text - this preserves the clickable anchor.
            document.querySelectorAll('[data-i18n]').forEach(el => {
                const key = el.getAttribute('data-i18n');
                if (window.translations[lang][key] !== undefined) {
                    const anchor = el.querySelector('a');
                    if (anchor) {
                        anchor.textContent = window.translations[lang][key];
                    } else {
                        el.textContent = window.translations[lang][key];
                    }
                }
            });

            // Update all data-i18n-placeholder elements
            document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
                const key = el.getAttribute('data-i18n-placeholder');
                if (window.translations[lang][key] !== undefined) {
                    el.placeholder = window.translations[lang][key];
                }
            });

            // Update all data-i18n-alt elements
            document.querySelectorAll('[data-i18n-alt]').forEach(el => {
                const key = el.getAttribute('data-i18n-alt');
                if (window.translations[lang][key] !== undefined) {
                    el.alt = window.translations[lang][key];
                }
            });

            // Update language buttons
            document.querySelectorAll('.lang-btn').forEach(btn => {
                btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
            });

            // Re-render modal if open and modal is visible
            if (document.getElementById('productModal').classList.contains('active')) {
                const modalBody = document.getElementById('modalBody');
                const visibleContent = modalBody.getAttribute('data-product-key');
                if (visibleContent) {
                    openModal(visibleContent);
                }
            }
        }

        // ─── Search ───
        function searchProducts(query) {
            query = query.trim().toLowerCase();
            const cards = document.querySelectorAll('.product-card');
            const sections = document.querySelectorAll('.cat-section');
            const noResults = document.querySelector('.search-no-results');

            if (!query) {
                cards.forEach(c => c.classList.remove('hidden'));
                sections.forEach(s => s.classList.remove('no-results'));
                if (noResults) noResults.style.display = 'none';
                return;
            }

            let matchCount = 0;
            cards.forEach(card => {
                const text = card.textContent.toLowerCase();
                if (text.includes(query)) {
                    card.classList.remove('hidden');
                    matchCount++;
                } else {
                    card.classList.add('hidden');
                }
            });

            sections.forEach(section => {
                const visibleCards = section.querySelectorAll('.product-card:not(.hidden)');
                section.classList.toggle('no-results', visibleCards.length === 0);
            });

            if (noResults) {
                noResults.style.display = matchCount === 0 ? 'block' : 'none';
            }
        }

        // ─── Category Navigation ───
        function initCategoryNav() {
            const navItems = document.querySelectorAll('.cat-nav-item');
            const sections = document.querySelectorAll('.cat-section');

            // Smooth scroll on nav click
            navItems.forEach(item => {
                item.addEventListener('click', (e) => {
                    e.preventDefault();
                    const target = item.getAttribute('data-target');
                    const section = document.getElementById(target);
                    if (section) {
                        section.scrollIntoView({ behavior: 'smooth', block: 'start' });
                        // Update active state
                        navItems.forEach(n => n.classList.remove('active'));
                        item.classList.add('active');
                    }
                });
            });

            // Update active nav on scroll
            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        const id = entry.target.id;
                        navItems.forEach(item => {
                            item.classList.toggle('active', item.getAttribute('data-target') === id);
                        });
                    }
                });
            }, { threshold: 0.3, rootMargin: '-100px 0px -50% 0px' });

            sections.forEach(section => observer.observe(section));
        }

        // Initialize on load
        document.addEventListener('DOMContentLoaded', initCategoryNav);

