(function(){
  function makeDraggable(el){
    var key = 'floatPos_' + (el.id || (el.className||'').split(/\s+/).filter(Boolean).join('_'));
    var ps = null, hasMoved = false, isDown = false, hrefBackup = null;
    try {
      var s = JSON.parse(localStorage.getItem(key) || 'null');
      if (s && typeof s.left === 'number' && typeof s.bottom === 'number') {
        el.style.left = s.left + 'px';
        el.style.bottom = s.bottom + 'px';
        el.style.right = 'auto';
      }
    } catch(e){}
    el.style.setProperty('cursor', 'grab', 'important');
    el.style.touchAction = 'none';
    el.style.userSelect = 'none';
    el.style.webkitUserSelect = 'none';
    el.addEventListener('pointerdown', function(e){
      if (e.pointerType === 'mouse' && e.button !== 0) return;
      isDown = true; hasMoved = false;
      var r = el.getBoundingClientRect();
      ps = { x: e.clientX, y: e.clientY, left: r.left, bottom: window.innerHeight - r.bottom };
      try { el.setPointerCapture(e.pointerId); } catch(err){}
      el.style.transition = 'none';
      el.style.setProperty('cursor', 'grabbing', 'important');
      // Strip href during drag for <a> elements so the browser can't navigate
      if (el.tagName === 'A' && el.hasAttribute('href')) {
        hrefBackup = el.getAttribute('href');
        el.removeAttribute('href');
      }
      // Prevent default to suppress native drag/text-select start
      if (e.cancelable) e.preventDefault();
    });
    el.addEventListener('pointermove', function(e){
      if (!isDown || !ps) return;
      var dx = e.clientX - ps.x, dy = e.clientY - ps.y;
      if (!hasMoved && (Math.abs(dx) > 3 || Math.abs(dy) > 3)) hasMoved = true;
      if (!hasMoved) return;
      var r = el.getBoundingClientRect();
      var nl = Math.max(0, Math.min(window.innerWidth - r.width, ps.left + dx));
      var nb = Math.max(0, Math.min(window.innerHeight - r.height, ps.bottom - dy));
      el.style.left = nl + 'px';
      el.style.bottom = nb + 'px';
      el.style.right = 'auto';
    });
    function end(e){
      if (!isDown) return;
      isDown = false;
      try { el.releasePointerCapture(e.pointerId); } catch(err){}
      el.style.setProperty('cursor', 'grab', 'important');
      el.style.transition = '';
      if (hasMoved) {
        var r = el.getBoundingClientRect();
        var cx = r.left + r.width / 2;
        var tl = cx < window.innerWidth / 2 ? 16 : window.innerWidth - r.width - 16;
        var tb = Math.max(16, Math.min(window.innerHeight - r.height - 16, window.innerHeight - r.bottom));
        el.style.transition = 'left .25s ease, bottom .25s ease';
        el.style.left = tl + 'px';
        el.style.bottom = tb + 'px';
        setTimeout(function(){ el.style.transition = ''; }, 260);
        try { localStorage.setItem(key, JSON.stringify({ left: tl, bottom: tb })); } catch(err){}
      } else if (hrefBackup) {
        // Pure click (no movement) — re-enable navigation
        el.setAttribute('href', hrefBackup);
      }
      hrefBackup = null;
      ps = null;
    }
    el.addEventListener('pointerup', end);
    el.addEventListener('pointercancel', end);
    el.addEventListener('click', function(e){
      if (hasMoved) {
        e.preventDefault();
        e.stopPropagation();
        e.stopImmediatePropagation();
      }
      hasMoved = false;
    }, true);
    // Suppress browser-native drag (image/selection) on the element
    el.addEventListener('dragstart', function(e){ e.preventDefault(); });
  }
  function init(){
    var wa = document.getElementById('floatingWhatsApp');
    var qb = document.querySelector('.float-quote-btn');
    if (wa) makeDraggable(wa);
    if (qb) makeDraggable(qb);
  }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
